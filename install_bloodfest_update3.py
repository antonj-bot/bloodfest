def _unpack(b64) -> dict:
    return json.loads(zlib.decompress(base64.b64decode("".join(b64))).decode("utf-8"))


HUNKS, FULL = _unpack(_HUNKS_B64), _unpack(_FULL_B64)


class Doc:
    """A text file held in memory, edited with LF newlines, written back in its original style."""

    def __init__(self, root: Path, rel: str) -> None:
        self.rel, self.path = rel, root / rel
        self.exists = self.path.exists()
        raw = self.path.read_bytes().decode("utf-8") if self.exists else ""
        self.crlf = "\r\n" in raw
        self.orig = raw.replace("\r\n", "\n")
        self.text = self.orig

    @property
    def changed(self) -> bool:
        return self.text != self.orig

    def output(self) -> bytes:
        return (self.text.replace("\n", "\r\n") if self.crlf else self.text).encode("utf-8")


def apply_hunk(text: str, old: str, new: str) -> tuple[str, str]:
    oc, nc = text.count(old), text.count(new)
    if nc == 1 and (oc == 0 or old in new):
        return text, SKIP
    if oc == 1 and (nc == 0 or old in new):
        return text.replace(old, new), OK
    return text, FAIL


def json_merge(doc: Doc, updates: dict, deletes: list[str]) -> str:
    try:
        data = json.loads(doc.text)
    except ValueError:
        return FAIL
    changed = False

    def apply(node: dict, upd: dict) -> None:
        nonlocal changed
        for k, v in upd.items():
            if isinstance(v, dict) and isinstance(node.get(k), dict):
                apply(node[k], v)
            elif node.get(k) != v:
                node[k] = v
                changed = True

    apply(data, updates)
    for path in deletes:                      # dotted paths, e.g. "storm" or "a.b"
        *parents, last = path.split(".")
        node = data
        for key in parents:
            node = node.get(key) if isinstance(node, dict) else None
        if isinstance(node, dict) and last in node:
            del node[last]
            changed = True
    if not changed:
        return SKIP
    doc.text = json.dumps(data, indent=2) + "\n"
    return OK


def plan(root: Path):
    """-> (docs, rows) ; rows = [(file, description, status, required)]"""
    docs: dict[str, Doc] = {}
    rows: list[tuple[str, str, str, bool]] = []

    def D(rel: str) -> Doc:
        return docs.setdefault(rel, Doc(root, rel))

    for rel, hunks in HUNKS.items():
        required = rel not in OPTIONAL_FILES
        d = D(rel)
        if not d.exists:
            rows.append((rel, f"{len(hunks)} change(s)", (FAIL + " (file not found)") if required else "skipped (file not found)", required))
            continue
        counts, bad = {OK: 0, SKIP: 0}, []
        for i, (old, new, line) in enumerate(hunks, 1):
            d.text, st = apply_hunk(d.text, old, new)
            if st == FAIL:
                bad.append(f"change {i}/{len(hunks)} near line {line}")
            else:
                counts[st] += 1
        if bad and not required:
            d.text = d.orig                    # all-or-nothing per optional file
            rows.append((rel, f"{len(hunks)} change(s)", "skipped (edited by hand - optional, left alone)", False))
        elif bad:
            rows.append((rel, f"{len(hunks)} change(s)", FAIL + ": " + "; ".join(bad), True))
        elif counts[OK] == 0:
            rows.append((rel, f"{len(hunks)} change(s)", SKIP, required))
        else:
            rows.append((rel, f"{len(hunks)} change(s)", f"{OK} ({counts[OK]} new, {counts[SKIP]} already there)", required))

    for rel, updates in JSON_UPDATES.items():
        d = D(rel)
        st = json_merge(d, updates, JSON_DELETES.get(rel, [])) if d.exists else FAIL + " (file not found)"
        rows.append((rel, "data changes", st, True))
    return docs, rows


def prerequisites(root: Path) -> str | None:
    need = {"server/game/world.py": "class Pickup", "server/game/match.py": "round_hard_cap_seconds",
            "client/game.js": "art: everything is drawn"}
    for rel, marker in need.items():
        p = root / rel
        if not p.exists():
            return f"missing {rel}"
        text = p.read_text(encoding="utf-8")
        if rel == "server/game/world.py" and marker not in text:
            return "this project does not have install_bloodfest_update2.py applied yet - run that one first"
        if rel == "client/game.js" and marker not in text:
            return "this project does not have install_bloodfest_update.py applied yet - run that one first"
    return None


def validate(docs: dict[str, Doc]) -> list[str]:
    problems = []
    for rel, d in docs.items():
        if not d.changed:
            continue
        try:
            if rel.endswith(".py"):
                compile(d.text, rel, "exec")
            elif rel.endswith(".json"):
                json.loads(d.text)
        except (SyntaxError, ValueError) as exc:
            problems.append(f"{rel}: {exc}")
    js = docs.get("client/game.js")
    if js and js.changed and shutil.which("node"):
        with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as fh:
            fh.write(js.text)
        r = subprocess.run(["node", "--check", fh.name], capture_output=True, text=True)
        if r.returncode:
            problems.append("client/game.js: " + (r.stderr.strip().splitlines() or ["syntax error"])[0])
    return problems


def find_root(arg: Path | None) -> Path:
    if arg:
        return arg.resolve()
    cwd = Path.cwd()
    for c in (cwd, cwd / "Bloodfest", cwd / "bloodfest"):
        if (c / "server" / "game" / "match.py").exists():
            return c.resolve()
    raise SystemExit("Could not find the Bloodfest project (server/game/match.py). "
                     "Run this from the Bloodfest folder, or pass --dir.")


def main() -> int:
    ap = argparse.ArgumentParser(description="Update Bloodfest in place (remove the storm, add a plain round timer).")
    ap.add_argument("--dir", type=Path, default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--test", action="store_true", help="run pytest in .venv afterwards")
    ap.add_argument("--overwrite-mismatched", action="store_true",
                    help="replace code files whose changes don't fit with the new versions (backup kept)")
    args = ap.parse_args()

    root = find_root(args.dir)
    print(f"Project: {root}" + ("   [DRY RUN]" if args.dry_run else ""))
    problem = prerequisites(root)
    if problem:
        print(f"\nSTOPPED - nothing was written: {problem}.")
        return 1

    docs, rows = plan(root)
    failed = [r for r in rows if r[2].startswith(FAIL) and r[3]]
    if failed and args.overwrite_mismatched:
        for rel in [r[0] for r in failed]:
            if rel in FULL:
                docs[rel].text = FULL[rel]
                rows = [(f, de, (OK + " (file replaced)") if f == rel and s.startswith(FAIL) else s, rq)
                        for f, de, s, rq in rows]
        failed = [r for r in rows if r[2].startswith(FAIL) and r[3]]

    w = max(len(r[0]) for r in rows)
    for rel, desc, status, req in rows:
        mark = {"applied": "+", "already applied": "="}.get(status.split(" (")[0].split(":")[0], "!")
        print(f"  {mark} {rel:<{w}}  {desc}: {status}")

    if failed:
        print("\nSTOPPED - nothing was written. Your file differs from the version this update expects:")
        for rel, _, status, _ in failed:
            print(f"   - {rel}")
        print("Options:\n  * send me that file (or the failing section), or\n"
              "  * re-run with --overwrite-mismatched to replace just those files with the new versions\n"
              "    (a backup is kept; custom edits in those files would be lost).")
        return 1

    problems = validate(docs)
    if problems:
        print("\nSTOPPED - the updated result failed validation, nothing was written:")
        for p in problems:
            print("   -", p)
        return 1

    changed = [d for d in docs.values() if d.changed]
    print(f"\n{len(changed)} file(s) to change, {len(docs) - len(changed)} already up to date.")
    if args.dry_run:
        print("Dry run only - nothing was written.")
        return 0
    if not changed:
        print("Nothing to do - Bloodfest already has this update.")
    else:
        backup = root / ".installer_backups" / dt.datetime.now().strftime("%Y%m%d_%H%M%S")
        for d in changed:
            if d.exists:
                (backup / d.rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(d.path, backup / d.rel)
            d.path.parent.mkdir(parents=True, exist_ok=True)
            d.path.write_bytes(d.output())
        print(f"Done. Backups: {backup}")

    if args.test:
        win = root / ".venv" / "Scripts" / "python.exe"
        nix = root / ".venv" / "bin" / "python"
        py = win if win.exists() else (nix if nix.exists() else Path(sys.executable))
        print(f"\n> {py} -m pytest -q")
        return subprocess.call([str(py), "-m", "pytest", "-q", "-p", "no:warnings"], cwd=root)
    print("\nRestart the server and hard-refresh the browser (Ctrl+F5):")
    print("  python -m uvicorn server.main:app --reload --port 8000")
    return 0


if __name__ == "__main__":
    sys.exit(main())
